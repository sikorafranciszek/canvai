function cssName(token: string): string {
  return token.replace(/^--/, '')
}

/** `tailwind.config.js` (Tailwind v3) — `theme.extend` z tokenów. */
export function renderTailwindConfig(spec: DesignSpec): string {
  const colorKey = (token: string) => cssName(token).replace(/^color-/, '')
  const extend = {
    colors: Object.fromEntries(spec.colors.map((c) => [colorKey(c.token), c.hex])),
    fontFamily: Object.fromEntries(
      spec.typography.families.map((f) => [
        cssName(f.token).replace(/^font-/, ''),
        [f.name, ...(f.substitute ? f.substitute.split(',').map((x) => x.trim()) : ['sans-serif'])],
      ])
    ),
    fontSize: Object.fromEntries(
      spec.typography.scale.map((r) => [
        cssName(r.token).replace(/^text-/, ''),
        r.lineHeight === '—' ? r.size : [r.size, { lineHeight: r.lineHeight }],
      ])
    ),
    spacing: Object.fromEntries(spec.spacing.scale.map((s) => [key(s.name), s.value])),
    borderRadius: Object.fromEntries(spec.radii.map((r) => [key(r.name), r.value])),
    boxShadow: Object.fromEntries(spec.shadows.map((s) => [key(s.name), s.value])),
  }
  return [
    `/** ${spec.name} — Tailwind CSS v3 theme generated by canvai from DESIGN.md. */`,
    `/** @type {import('tailwindcss').Config} */`,
    `module.exports = {`,
    `  content: ['./src/**/*.{html,js,jsx,ts,tsx,vue,svelte,astro}'],`,
    `  theme: {`,
    `    extend: ${JSON.stringify(extend, null, 2).replace(/\n/g, '\n    ')},`,
    `  },`,
    `}`,
    '',
  ].join('\n')
}

/** Zmienne SCSS. */
export function renderScss(spec: DesignSpec): string {
  const lines = [`// ${spec.name} — design tokens generated by canvai`, '']
  const add = (title: string, entries: [string, string][]) => {
    if (!entries.length) return
    lines.push(`// ${title}`)
    for (const [k, v] of entries) lines.push(`$${k}: ${v};`)
    lines.push('')
  }
  add(
    'Colors',
    spec.colors.map((c) => [cssName(c.token), c.hex])
  )
  add(
    'Typography',
    spec.typography.families.map((f) => [
      cssName(f.token),
      `'${f.name.replace(/'/g, '')}', ${f.substitute || 'sans-serif'}`,
    ])
  )
  add(
    'Type scale',
    spec.typography.scale.map((r) => [cssName(r.token), r.size])
  )
  add(
    'Spacing',
    spec.spacing.scale.map((s) => [`spacing-${key(s.name)}`, s.value])
  )
  add(
    'Radius',
    spec.radii.map((r) => [`radius-${key(r.name)}`, r.value])
  )
  add(
    'Shadows',
    spec.shadows.map((s) => [`shadow-${key(s.name)}`, s.value])
  )
  return lines.join('\n')
}

/**
 * Tokens Studio for Figma (format JSON z `value`/`type`) — import w wtyczce
 * Tokens Studio tworzy zmienne i style w Figmie.
 */
export function renderTokensStudio(spec: DesignSpec): Record<string, unknown> {
  const set: Record<string, Record<string, unknown>> = {
    color: {},
    fontFamilies: {},
    fontSizes: {},
    lineHeights: {},
    spacing: {},
    borderRadius: {},
    boxShadow: {},
  }
  for (const c of spec.colors)
    set.color[unique(set.color as Group, c.name)] = {
      value: c.hex,
      type: 'color',
      description: c.role,
    }
  for (const f of spec.typography.families)
    set.fontFamilies[unique(set.fontFamilies as Group, f.name)] = {
      value: f.name,
      type: 'fontFamilies',
    }
  for (const r of spec.typography.scale) {
    set.fontSizes[unique(set.fontSizes as Group, r.role)] = { value: r.size, type: 'fontSizes' }
    if (r.lineHeight !== '—')
      set.lineHeights[unique(set.lineHeights as Group, r.role)] = {
        value: r.lineHeight,
        type: 'lineHeights',
      }
  }
  for (const s of spec.spacing.scale)
    set.spacing[unique(set.spacing as Group, s.name)] = { value: s.value, type: 'spacing' }
  for (const r of spec.radii)
    set.borderRadius[unique(set.borderRadius as Group, r.name)] = {
      value: r.value,
      type: 'borderRadius',
    }
  for (const sh of spec.shadows)
    set.boxShadow[unique(set.boxShadow as Group, sh.name)] = { value: sh.value, type: 'boxShadow' }
  return {
    [key(spec.name) || 'canvai']: set,
    $themes: [],
    $metadata: { tokenSetOrder: [key(spec.name) || 'canvai'] },
  }
}


/**
 * Zwięzła ściągawka systemu (tokeny, typografia, zasady, dostępność) —
 * wspólna dla reguł Cursora, CLAUDE.md, AGENTS.md i promptu v0/Lovable.
 * Pełna specyfikacja zostaje w DESIGN.md.
 */
export function condensedGuide(spec: DesignSpec): string {
  const lines: string[] = []
  lines.push(`Theme: ${spec.theme}. ${spec.tagline}`.trim())
  lines.push('', '### Colors (use the tokens, never raw hex)')
  for (const c of spec.colors) lines.push(`- \`${c.token}\` ${c.hex} — ${c.name}: ${c.role}`)
  lines.push('', '### Typography')
  for (const f of spec.typography.families) {
    lines.push(
      `- \`${f.token}\`: ${f.name}${f.substitute ? ` (fallback ${f.substitute})` : ''} — ${f.role}`
    )
  }
  for (const r of spec.typography.scale) {
    lines.push(
      `- ${r.role}: ${r.size}${r.lineHeight !== '—' ? `/${r.lineHeight}` : ''}, weight ${r.weight} (\`${r.token}\`)`
    )
  }
  const shape = [
    `base unit ${spec.spacing.baseUnit} (${spec.spacing.density})`,
    ...spec.radii.map((r) => `radius ${r.name} ${r.value}`),
    ...spec.shadows.map((s) => `shadow ${s.name}: ${s.value}`),
  ]
  lines.push('', '### Spacing & shape', ...shape.map((x) => `- ${x}`))
  if (spec.components.length) {
    lines.push('', '### Components')
    for (const c of spec.components.slice(0, 14))
      lines.push(`- **${c.name}**: ${c.description.replace(/\s+/g, ' ').slice(0, 280)}`)
  }
  lines.push('', '### Do', ...spec.dos.map((d) => `- ${d}`))
  lines.push('', "### Don't", ...spec.donts.map((d) => `- ${d}`))
  lines.push(
    '',
    '### Accessibility',
    '- Body text contrast ≥ 4.5:1 (WCAG AA); visible focus ring on every interactive element.',
    '- Respect prefers-reduced-motion; hit targets ≥ 24×24px (44px on touch).'
  )
  return lines.join('\n')
}

const RULES_INTRO =
  'This project has a design system. Build every UI with its tokens and rules; the complete specification (components, states, screens, voice) is in `DESIGN.md` at the repository root — read it before creating or changing UI.'

export function renderCursorRules(spec: DesignSpec): string {
  return [
    '---',
    `description: ${spec.name} design system — tokens, typography, components and UI rules`,
    'globs: "**/*.{tsx,jsx,vue,svelte,astro,html,css,scss}"',
    'alwaysApply: false',
    '---',
    '',
    `# ${spec.name} design system`,
    '',
    RULES_INTRO,
    '',
    condensedGuide(spec),
    '',
  ].join('\n')
}

export function renderClaudeMd(spec: DesignSpec): string {
  return [
    `# Design system — ${spec.name}`,
    '',
    RULES_INTRO,
    '',
    'Full specification: @DESIGN.md',
    '',
    condensedGuide(spec),
    '',
  ].join('\n')
}

export function renderAgentsMd(spec: DesignSpec): string {
  return [
    `# AGENTS.md — UI and design system (${spec.name})`,
    '',
    RULES_INTRO,
    '',
    condensedGuide(spec),
    '',
  ].join('\n')
}

/** Prompt do wklejenia w v0 / Lovable / Bolt (bez dostępu do plików repozytorium). */
export function renderBuilderPrompt(spec: DesignSpec): string {
  return [
    `Build the UI for "${spec.name}" following this design system exactly. Use only these colors, fonts, sizes, radii and shadows (define them as CSS variables / Tailwind theme), apply the component descriptions and the do/don't rules, keep text contrast at WCAG AA.`,
    '',
    spec.overview
      .replace(/\[A\d+\]/g, '')
      .replace(/\s+/g, ' ')
      .trim(),
    '',
    condensedGuide(spec),
    '',
    'Start with the most representative screen, responsive (mobile first). Use realistic copy, no lorem ipsum.',
    '',
  ].join('\n')
}

export const EXPORT_FORMATS = [
  'css',
  'tailwind',
  'tokens',
  'tailwind3',
  'scss',
  'figma',
  'cursor',
  'claude',
  'agents',
  'prompt',
] as const

export type ExportFormat = (typeof EXPORT_FORMATS)[number]

/** Plik eksportu (nazwa, typ, treść) — wspólny dla UI, REST v1 i MCP. */
export function renderExport(spec: DesignSpec, format: ExportFormat) {
  switch (format) {
    case 'css':
      return { name: 'tokens.css', type: 'text/css', body: renderCssVariables(spec) + '\n' }
    case 'tailwind':
      return {
        name: 'theme.css',
        type: 'text/css',
        body: `@import "tailwindcss";\n\n${renderTailwindTheme(spec)}\n`,
      }
    case 'tokens':
      return {
        name: 'design-tokens.json',
        type: 'application/json',
        body: JSON.stringify(renderDesignTokens(spec), null, 2) + '\n',
      }
    case 'tailwind3':
      return {
        name: 'tailwind.config.js',
        type: 'text/javascript',
        body: renderTailwindConfig(spec),
      }
    case 'scss':
      return { name: '_tokens.scss', type: 'text/x-scss', body: renderScss(spec) }
    case 'figma':
      return {
        name: 'tokens-studio.json',
        type: 'application/json',
        body: JSON.stringify(renderTokensStudio(spec), null, 2) + '\n',
      }
    case 'cursor':
      return { name: 'design-system.mdc', type: 'text/markdown', body: renderCursorRules(spec) }
    case 'claude':
      return { name: 'CLAUDE.md', type: 'text/markdown', body: renderClaudeMd(spec) }
    case 'agents':
      return { name: 'AGENTS.md', type: 'text/markdown', body: renderAgentsMd(spec) }
    case 'prompt':
      return { name: 'prompt.txt', type: 'text/plain', body: renderBuilderPrompt(spec) }
  }
}
